/**
 * Pack nights generated by the real orchestrator and decision store, with fake players and a
 * scripted Jev, so events arrive in the order production writes them (team.point, then the
 * journal update, then decision.committed) under both protocol versions.
 */
const directories: string[] = [];
afterEach(() => {
  while (directories.length) rmSync(directories.pop()!, { recursive: true, force: true });
});

type Protocol = "agent_v3_2" | "agent_v3_1";
/** A wolf's point in one round: at the victim or another villager, with its probability. */
type Point = { at: "victim" | "other"; p: number };
interface NightScript {
  protocol?: Protocol;
  /** Each round's points, by wolf (in seat order); the pack converges when both name one. */
  rounds: [Point, Point][];
  /** The doctor protects the victim (a save). */
  save?: boolean;
  /** A private result only the first wolf receives before the night. */
  wolfInspection?: boolean;
}

const choice = (handles: string[], pick: string, p: number) => ({
  type: "choice",
  choice: pick,
  confidence: 1,
  probabilities: Object.fromEntries(
    handles.map((h) => [h, h === pick ? p : (1 - p) / (handles.length - 1)]),
  ),
});

function config(protocol: Protocol) {
  return GameConfigV2Schema.parse({
    ...actorConfig(),
    protocolVersion: protocol,
    decisionEngine: {
      mode: "jev",
      workflow: protocol === "agent_v3_2" ? "journal_v4" : "journal_v3",
    },
  });
}

/** Runs one real game up to its first dawn and returns it on disk for the analyzer. */
async function packNight(script: NightScript) {
  const directory = mkdtempSync(join(tmpdir(), "pack-night-"));
  directories.push(directory);
  const dbPath = join(directory, "game.db");
  const connection = openDatabase(dbPath);
  const repository = new LabRepository(connection);
  const game = repository.createGame(config(script.protocol ?? "agent_v3_2"));
  new V2GameOrchestrator(repository, new FakeDecisionProvider()).initialize(game.id);
  const state = reduceGame(game.id, repository.listEvents(game.id));
  const wolves = state.players.filter((p) => p.role.alignment === "werewolf").map((p) => p.id);
  const villagers = state.players.filter((p) => p.role.id === "villager").map((p) => p.id);
  const [victim, other] = villagers as [string, string];
  const seer = state.players.find((p) => p.role.id === "seer")!.id;
  const doctor = state.players.find((p) => p.role.id === "doctor")!.id;
  let wolfInspectionId: string | undefined;
  if (script.wolfInspection) {
    repository.appendEvent(game.id, {
      day: state.day,
      phase: state.phase,
      type: "inspection.delivered",
      visibility: "player",
      audienceIds: [wolves[0]!],
      payload: { actorId: wolves[0], targetId: seer, targetName: "seer", result: "village" },
    });
    wolfInspectionId = repository.listEvents(game.id).at(-1)!.id;
  }
  const rounds = new Map<string, number>();
  const jev = new AskJevProvider(async (input) => {
    const request = JSON.parse(input) as JevRequest;
    const self = /\((p\d+)\), /.exec(JSON.stringify(request))?.[1] ?? "";
    const answers = Object.fromEntries(
      Object.entries(request.questions).map(([key, q]) => {
        if (q.type === "noul") return [key, { type: "noul", noul: 0 }];
        if (q.type === "score")
          return [
            key,
            {
              type: "score",
              score: 3,
              confidence: 1,
              probabilities: { 0: 0, 1: 0, 2: 0, 3: 1, 4: 0 },
            },
          ];
        // V3.2 criteria are text naming "(pN)"; V3.1 criteria are { playerId, name } objects.
        const criteria = q.criteria as Record<string, string | { playerId?: string }>;
        const handles = Object.keys(criteria);
        const of = (id: string) =>
          handles.find((h) => {
            const option = criteria[h]!;
            return typeof option === "string" ? option.includes(`(${id})`) : option.playerId === id;
          });
        // The first night is the only one run: a wolf's choice is its pack point, the doctor's
        // its protection.
        if (wolves.includes(self)) {
          const round = rounds.get(self) ?? 0;
          rounds.set(self, round + 1);
          const planned = script.rounds[Math.min(round, script.rounds.length - 1)]!;
          const point = planned[wolves.indexOf(self)]!;
          return [key, choice(handles, of(point.at === "victim" ? victim : other)!, point.p)];
        }
        if (self === doctor) {
          const pick = script.save ? of(victim) : handles.find((h) => h !== of(victim));
          return [key, choice(handles, pick ?? handles[0]!, 0.9)];
        }
        return [key, choice(handles, handles[0]!, 0.9)];
      }),
    );
    return JSON.stringify({ model: "fake", usage: { input_tokens: 1, output_tokens: 1 }, answers });
  });
  const runner = new V2GameOrchestrator(repository, new FakeDecisionProvider(), jev);
  repository.updateGame(game.id, { status: "running" });
  const dawned = () => repository.listEvents(game.id).some((e) => e.type === "night.resolved");
  for (let step = 0; step < 60 && !dawned(); step += 1) await runner.runGameStep(game.id);
  const store = new DecisionStore(repository);
  /** Each wolf's kill points, in commit order. */
  const points = (wolf: string) =>
    store
      .opportunities(game.id)
      .filter((op) => op.taskType === "team_point_choice" && op.playerId === wolf)
      .map((op) => ({
        op,
        sequence: repository
          .listEvents(game.id)
          .find((e) => e.type === "decision.committed" && e.payload.decisionId === op.id)!.sequence,
      }))
      .sort((a, b) => a.sequence - b.sequence)
      .map((entry) => entry.op);
  const agreement = repository.listEvents(game.id).find((e) => e.type === "team.agreement_frozen");
  const finalOps = Object.fromEntries(wolves.map((w) => [w, points(w).at(-1)!])) as Record<
    string,
    DecisionOpportunityV1
  >;
  const done = dawned();
  connection.close();
  return {
    dbPath,
    gameId: game.id,
    directory,
    wolves,
    victim,
    seer,
    wolfInspectionId,
    agreementId: agreement?.id,
    finalOps,
    dawned: done,
  };
}
type Night = Awaited<ReturnType<typeof packNight>>;

/** Edits the stored game the way a damaged or partial record would look. */
function edit(night: Night, change: (sql: LabRepository["connection"]["sqlite"]) => void) {
  const connection = openDatabase(night.dbPath);
  change(connection.sqlite);
  connection.close();
}

/** The analyzer's public dawn prediction: the victim is unexpected, no death is likely. */
function dawnJev(victim: string): DecisionProvider {
  return {
    decide: async (request) => {
      const jevRequest = JSON.parse(request.preparedPrompt!.input) as JevRequest;
      const criteria = (jevRequest.questions.prediction as { criteria: Record<string, string> })
        .criteria;
      const handles = Object.keys(criteria);
      const weight = (h: string) =>
        h === "no_death" ? 0.9 : criteria[h]!.includes(`(${victim})`) ? 0.05 : 0;
      const rest = 1 - handles.reduce((sum, h) => sum + weight(h), 0);
      const others = handles.filter((h) => weight(h) === 0);
      const probabilities = Object.fromEntries(
        handles.map((h) => [h, weight(h) || rest / Math.max(1, others.length)]),
      );
      return {
        data: {
          model: "jev-latest",
          answers: {
            prediction: { type: "choice", choice: "no_death", confidence: 1, probabilities },
          },
        } as never,
        provider: "jev",
        model: "jev-latest",
        usage: { inputTokens: 10, outputTokens: 5, totalTokens: 15 },
      };
    },
  };
}

const plain = (): MomentReview =>
  ({
    explanation: "Routine.",
    citedEventIds: [],
    knowledgeClaims: [],
    groundTruth: "",
    regressionCandidate: false,
  }) as MomentReview;

async function analyze(night: Night, review: () => MomentReview = plain) {
  const dossiers: Record<string, unknown>[] = [];
  const reviewer: DecisionProvider = {
    decide: async (request) => {
      dossiers.push(JSON.parse(request.preparedPrompt!.input));
      return {
        data: review() as never,
        provider: "fake",
        model: "review",
        usage: { inputTokens: 900, outputTokens: 100, totalTokens: 1_000 },
      };
    },
  };
  const report = await analyzeGame({
    dbPath: night.dbPath,
    gameId: night.gameId,
    outDir: join(night.directory, "analysis"),
    jev: dawnJev(night.victim),
    jevModel: "jev-latest",
    review: { provider: reviewer, kind: "fake", model: "review" },
  });
  const kills = report.moments.filter((m) => m.kind === "night_action");
  return { report, kills, dossiers };
}

type Kill = {
  actual: string;
  selected?: string;
  class: string;
  noSignalReason?: string;
  score: { privateProbability: number };
  wolfProbabilities?: Record<string, number>;
};
const values = (record: Record<string, number> | undefined) =>
  Object.values(record ?? {}).sort((a, b) => a - b);

describe.each(["agent_v3_2", "agent_v3_1"] as const)("pack nights under %s", (protocol) => {
  it("scores a first-round unanimous kill on the dawn, with the wolves' mean", async () => {
    const night = await packNight({
      protocol,
      rounds: [
        [
          { at: "victim", p: 0.9 },
          { at: "victim", p: 0.7 },
        ],
      ],
    });
    expect(night.dawned).toBe(true);
    const { kills } = await analyze(night);
    expect(kills).toHaveLength(1);
    const kill = kills[0] as unknown as Kill;
    expect(kill).toMatchObject({
      actual: night.victim,
      selected: night.victim,
      class: "private_knowledge",
    });
    expect(kill.score.privateProbability).toBeCloseTo(0.8, 10);
    expect(values(kill.wolfProbabilities)).toEqual([0.7, 0.9]);
  });

  it("scores only the final round after a split one", async () => {
    // halcyon's control: a split first round, then 0.9 and 0.7 on the victim, who dies.
    const night = await packNight({
      protocol,
      rounds: [
        [
          { at: "victim", p: 0.6 },
          { at: "other", p: 0.6 },
        ],
        [
          { at: "victim", p: 0.9 },
          { at: "victim", p: 0.7 },
        ],
      ],
    });
    const { kills } = await analyze(night);
    expect(kills).toHaveLength(1);
    const kill = kills[0] as unknown as Kill;
    expect(kill).toMatchObject({ selected: night.victim, class: "private_knowledge" });
    expect(kill.score.privateProbability).toBeCloseTo(0.8, 10);
    expect(values(kill.wolfProbabilities)).toEqual([0.7, 0.9]);
  });
});

describe("pack night signal and membership", () => {
  const unanimous: NightScript["rounds"] = [
    [
      { at: "victim", p: 0.9 },
      { at: "victim", p: 0.7 },
    ],
  ];

  it("marks a saved kill no_signal", async () => {
    const night = await packNight({ rounds: unanimous, save: true });
    const { kills } = await analyze(night);
    expect(kills).toHaveLength(1);
    expect(kills[0]).toMatchObject({
      actual: "no_death",
      selected: night.victim,
      class: "no_signal",
      noSignalReason: expect.stringContaining("save"),
    });
  });

  it("marks a pack that never agrees no_signal", async () => {
    const night = await packNight({
      rounds: [
        [
          { at: "victim", p: 0.6 },
          { at: "other", p: 0.6 },
        ],
      ],
    });
    const { kills } = await analyze(night);
    expect(kills).toHaveLength(1);
    expect(kills[0]).toMatchObject({
      class: "no_signal",
      noSignalReason: expect.stringContaining("not unanimous"),
    });
  });

  it("never falls back to an earlier round when a final-round record is missing", async () => {
    const night = await packNight({
      rounds: [
        [
          { at: "victim", p: 0.6 },
          { at: "other", p: 0.6 },
        ],
        unanimous[0]!,
      ],
    });
    edit(night, (sql) =>
      sql
        .prepare("DELETE FROM agent_records WHERE game_id=? AND record_key=?")
        .run(night.gameId, `decision:${night.finalOps[night.wolves[1]!]!.id}`),
    );
    const { kills } = await analyze(night);
    expect(kills).toHaveLength(1);
    expect(kills[0]).toMatchObject({
      class: "no_signal",
      noSignalReason: expect.stringContaining("incomplete pack"),
    });
  });

  it("marks a night no_signal when a final-round distribution is invalid", async () => {
    const night = await packNight({ rounds: unanimous });
    const connection = openDatabase(night.dbPath);
    const store = new DecisionStore(new LabRepository(connection));
    for (const attempt of store.attempts(night.gameId, night.finalOps[night.wolves[1]!]!.id))
      if (attempt.provider === "jev") store.updateAttempt({ ...attempt, status: "invalid" });
    connection.close();
    const { kills } = await analyze(night);
    expect(kills).toHaveLength(1);
    expect(kills[0]).toMatchObject({
      class: "no_signal",
      noSignalReason: expect.stringContaining("incomplete pack"),
    });
  });

  it("keeps a night whose final records are all missing, as no_signal", async () => {
    const night = await packNight({ rounds: unanimous });
    edit(night, (sql) => {
      for (const op of Object.values(night.finalOps))
        sql
          .prepare("DELETE FROM agent_records WHERE game_id=? AND record_key=?")
          .run(night.gameId, `decision:${op.id}`);
    });
    const { kills } = await analyze(night);
    expect(kills).toHaveLength(1);
    expect(kills[0]).toMatchObject({
      class: "no_signal",
      noSignalReason: expect.stringContaining("incomplete pack"),
    });
  });

  it.each([
    ["no decider", (_wolves: string[]) => [] as string[], "no deciders"],
    ["a duplicated decider", (wolves: string[]) => [wolves[0]!, wolves[0]!], "duplicated decider"],
  ])("marks a night with %s no_signal", async (_label, deciders, reason) => {
    const night = await packNight({ rounds: unanimous });
    edit(night, (sql) => {
      const row = sql
        .prepare("SELECT payload_json FROM events WHERE id=?")
        .get(night.agreementId) as { payload_json: string };
      const payload = { ...JSON.parse(row.payload_json), actorIds: deciders(night.wolves) };
      sql
        .prepare("UPDATE events SET payload_json=? WHERE id=?")
        .run(JSON.stringify(payload), night.agreementId);
    });
    const { kills } = await analyze(night);
    expect(kills).toHaveLength(1);
    expect(kills[0]).toMatchObject({
      class: "no_signal",
      noSignalReason: expect.stringContaining(reason),
    });
  });

  it("makes no moment for the seer's or doctor's night choices", async () => {
    const night = await packNight({ rounds: unanimous });
    const { report } = await analyze(night);
    expect(report.moments.map((m) => m.actorId)).not.toContain(night.seer);
    expect(report.moments.every((m) => m.kind === "night_action")).toBe(true);
    expect(report.moments).toHaveLength(1);
  });
});

describe("pack night reviews", () => {
  const split: NightScript["rounds"] = [
    [
      { at: "victim", p: 0.6 },
      { at: "other", p: 0.6 },
    ],
    [
      { at: "victim", p: 0.9 },
      { at: "victim", p: 0.7 },
    ],
  ];

  it("gives the reviewer each wolf's final-round briefing exactly as Jev received it", async () => {
    const night = await packNight({ rounds: split });
    const { dossiers } = await analyze(night);
    expect(dossiers).toHaveLength(1);
    const briefings = dossiers[0]!.actorBriefings as Record<string, unknown>;
    for (const wolf of night.wolves)
      expect(briefings[wolf]).toEqual(
        JSON.parse(JSON.stringify(actorBriefing(night.finalOps[wolf]!))),
      );
  });

  it("checks a pack claim against its subject wolf's own view", async () => {
    const night = await packNight({ rounds: split, wolfInspection: true });
    const [first, second] = night.wolves as [string, string];
    const claimed = (subjectId: string | null) => () =>
      ({
        ...plain(),
        knowledgeClaims: [
          { claim: "Knew the seer was village.", eventIds: [night.wolfInspectionId!], subjectId },
        ],
      }) as MomentReview;
    const status = async (review: () => MomentReview) =>
      (await analyze(night, review)).report.reviews[0]?.status;
    expect(await status(claimed(second))).toBe("rejected_citation");
    expect(await status(claimed(null))).toBe("rejected_citation");
    expect(await status(claimed(first))).toBe("accepted");
  });
});

/**
 * Damaged records (halcyon's fourth review): real orchestrator nights, then corrupted. Each must
 * give one no_signal moment naming the broken invariant; nothing is repaired or guessed.
 */
describe("pack nights with inconsistent records", () => {
  const unanimous: NightScript["rounds"] = [
    [
      { at: "victim", p: 0.9 },
      { at: "victim", p: 0.7 },
    ],
  ];
  type Sql = LabRepository["connection"]["sqlite"];
  type EventRow = Record<string, unknown> & { id: string; sequence: number };
  const eventRow = (sql: Sql, id: string) =>
    sql.prepare("SELECT * FROM events WHERE id=?").get(id) as EventRow;
  /** Opens a gap after `sequence` so a row can be inserted inside the night. */
  function shiftAfter(sql: Sql, gameId: string, sequence: number) {
    sql
      .prepare("UPDATE events SET sequence = -(sequence + 1) WHERE game_id=? AND sequence > ?")
      .run(gameId, sequence);
    sql
      .prepare("UPDATE events SET sequence = -sequence WHERE game_id=? AND sequence < 0")
      .run(gameId);
  }
  function insertCopy(sql: Sql, row: EventRow, id: string, sequence: number) {
    const { row_id: _rowId, ...fields } = row;
    const columns = Object.keys(fields);
    sql
      .prepare(
        `INSERT INTO events (${columns.join(", ")}) VALUES (${columns.map(() => "?").join(", ")})`,
      )
      .run(
        ...columns.map((column) =>
          column === "id" ? id : column === "sequence" ? sequence : fields[column],
        ),
      );
  }
  const inconsistent = async (night: Night, invariant: string) => {
    const { kills } = await analyze(night);
    expect(kills).toHaveLength(1);
    expect(kills[0]).toMatchObject({
      class: "no_signal",
      noSignalReason: expect.stringMatching(new RegExp(`inconsistent pack records.*${invariant}`)),
    });
  };

  it.each(["agent_v3_2", "agent_v3_1"] as const)(
    "keeps a pack kill whose freeze is missing, as no_signal (%s)",
    async (protocol) => {
      // halcyon's control: a real unanimous kill with only its freeze removed.
      const night = await packNight({ protocol, rounds: unanimous });
      edit(night, (sql) => sql.prepare("DELETE FROM events WHERE id=?").run(night.agreementId));
      await inconsistent(night, "missing freeze");
    },
  );

  it("refuses decisions attributed to the wrong wolf", async () => {
    // halcyon's control: the two wolves' commit payloads carry each other's decision IDs.
    const night = await packNight({ rounds: unanimous });
    edit(night, (sql) => {
      const [first, second] = night.wolves.map((wolf) => {
        const op = night.finalOps[wolf]!;
        return sql
          .prepare(
            "SELECT * FROM events WHERE game_id=? AND type='decision.committed' AND payload_json LIKE ?",
          )
          .get(night.gameId, `%"decisionId":"${op.id}"%`) as EventRow;
      }) as [EventRow, EventRow];
      const swap = (row: EventRow, decisionId: unknown) =>
        sql
          .prepare("UPDATE events SET payload_json=? WHERE id=?")
          .run(JSON.stringify({ ...JSON.parse(String(row.payload_json)), decisionId }), row.id);
      const ids = [first, second].map((row) => JSON.parse(String(row.payload_json)).decisionId);
      swap(first, ids[1]);
      swap(second, ids[0]);
    });
    await inconsistent(night, "ownership mismatch");
  });

  it("refuses a final decision committed after the freeze", async () => {
    // halcyon's future-record control: the wolf's decision now lands after the night.
    const night = await packNight({ rounds: unanimous });
    edit(night, (sql) => {
      const op = night.finalOps[night.wolves[1]!]!;
      const commit = sql
        .prepare(
          "SELECT * FROM events WHERE game_id=? AND type='decision.committed' AND payload_json LIKE ?",
        )
        .get(night.gameId, `%"decisionId":"${op.id}"%`) as EventRow;
      const last = sql
        .prepare("SELECT MAX(sequence) AS n FROM events WHERE game_id=?")
        .get(night.gameId) as { n: number };
      sql.prepare("DELETE FROM events WHERE id=?").run(commit.id);
      insertCopy(sql, commit, `${commit.id}-late`, last.n + 1);
    });
    await inconsistent(night, "after the freeze");
  });

  it("refuses a freeze naming fewer wolves than are alive", async () => {
    const night = await packNight({ rounds: unanimous });
    edit(night, (sql) => {
      const row = eventRow(sql, night.agreementId!);
      const payload = { ...JSON.parse(String(row.payload_json)), actorIds: [night.wolves[0]] };
      sql
        .prepare("UPDATE events SET payload_json=? WHERE id=?")
        .run(JSON.stringify(payload), row.id);
    });
    await inconsistent(night, "living wolves");
  });

  it("makes one moment for a night with a duplicated freeze", async () => {
    const night = await packNight({ rounds: unanimous });
    edit(night, (sql) => {
      const row = eventRow(sql, night.agreementId!);
      shiftAfter(sql, night.gameId, row.sequence);
      insertCopy(sql, row, `${row.id}-again`, row.sequence + 1);
    });
    await inconsistent(night, "2 agreements");
  });
});
